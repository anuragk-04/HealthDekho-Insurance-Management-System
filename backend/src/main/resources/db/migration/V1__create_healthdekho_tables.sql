
-- =====================================================
-- HealthDekho V1: Create database tables
-- PostgreSQL
-- =====================================================

-- 1. Customers
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    date_of_birth DATE NOT NULL,
    phone_number VARCHAR(15),
    created_at TIMESTAMP NOT NULL
);

-- 2. Insurance Products
CREATE TABLE insurance_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(30) NOT NULL UNIQUE,
    product_name VARCHAR(150) NOT NULL,
    insurance_type VARCHAR(50) NOT NULL,
    description VARCHAR(1000),
    min_age INTEGER NOT NULL,
    max_age INTEGER NOT NULL,
    min_term_years INTEGER NOT NULL,
    max_term_years INTEGER NOT NULL,
    premium_amount NUMERIC(12,2) NOT NULL,
    premium_frequency VARCHAR(30) NOT NULL,
    sum_insured NUMERIC(15,2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. AI Recommendation Requests
CREATE TABLE ai_recommendation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    date_of_birth DATE NOT NULL,
    goals_and_preferences VARCHAR(1000) NOT NULL,
    preferred_term_years INTEGER NOT NULL,
    preferred_insurance_type VARCHAR(50),
    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_ai_request_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
);

-- 4. Customer Policies
CREATE TABLE customer_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    maturity_date DATE NOT NULL,
    term_years INTEGER NOT NULL,
    premium_amount NUMERIC(12,2) NOT NULL,
    premium_frequency VARCHAR(30) NOT NULL,
    sum_insured NUMERIC(15,2) NOT NULL,
    total_premium NUMERIC(15,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT fk_policy_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id),

    CONSTRAINT fk_policy_product
        FOREIGN KEY (product_id)
        REFERENCES insurance_products(id),

    CONSTRAINT uk_customer_product
        UNIQUE (customer_id, product_id)
);

-- 5. Premium Installments
CREATE TABLE premium_installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_policy_id BIGINT NOT NULL,
    installment_number INTEGER NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT fk_installment_policy
        FOREIGN KEY (customer_policy_id)
        REFERENCES customer_policies(id),

    CONSTRAINT uk_policy_installment_number
        UNIQUE (customer_policy_id, installment_number)
);

-- 6. AI Recommendation Items
CREATE TABLE ai_recommendation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_request_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    rationale VARCHAR(2000) NOT NULL,
    suitability VARCHAR(500) NOT NULL,

    CONSTRAINT fk_recommendation_request
        FOREIGN KEY (recommendation_request_id)
        REFERENCES ai_recommendation_requests(id),

    CONSTRAINT fk_recommendation_product
        FOREIGN KEY (product_id)
        REFERENCES insurance_products(id)
);

-- =====================================================
-- Indexes for frequently queried foreign keys
-- =====================================================

CREATE INDEX idx_ai_request_customer
    ON ai_recommendation_requests(customer_id);

CREATE INDEX idx_policy_customer
    ON customer_policies(customer_id);

CREATE INDEX idx_policy_product
    ON customer_policies(product_id);

CREATE INDEX idx_installment_policy
    ON premium_installments(customer_policy_id);

CREATE INDEX idx_recommendation_request
    ON ai_recommendation_items(recommendation_request_id);

CREATE INDEX idx_recommendation_product
    ON ai_recommendation_items(product_id);
